  const page = document.body.dataset.page === "stockists" ? "stockists" : "home";

  function setLanguage(lang) {
    const selected = Object.prototype.hasOwnProperty.call(copy, lang) ? lang : "pt";
    const words = copy[selected];
    document.documentElement.lang = selected === "pt" ? "pt-PT" : "en";
    document.title = page === "stockists" ? words.pageTitleStockists : words.pageTitleHome;
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.content = page === "stockists" ? words.descriptionStockists : words.descriptionHome;

    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.dataset.i18n;
      if (typeof words[key] === "string") {
        if (key === "navContact") el.innerHTML = words[key];
        else el.textContent = words[key];
      }
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      const html = words[el.dataset.i18nHtml];
      if (typeof html === "string") el.innerHTML = html;
    });
    document.querySelectorAll("[data-lang-switch]").forEach(el => {
      el.setAttribute("aria-pressed", String(el.dataset.langSwitch === selected));
    });
    const menu = document.querySelector(".menu-button");
    if (menu) menu.setAttribute("aria-label", selected === "pt" ? "Abrir menu" : "Open menu");
    try { localStorage.setItem("smthng-language", selected); } catch (_) {}
  }

  let initial = "pt";
  try { initial = localStorage.getItem("smthng-language") || "pt"; } catch (_) {}
  if (!["pt","en"].includes(initial)) initial = "pt";
  setLanguage(initial);
  document.querySelectorAll("[data-lang-switch]").forEach(button => {
    button.addEventListener("click", () => setLanguage(button.dataset.langSwitch));
  });

  const menu = document.querySelector(".menu-button");
  const nav = document.getElementById("primary-nav");
  function closeMenu() {
    if (!menu || !nav) return;
    menu.setAttribute("aria-expanded", "false");
    nav.classList.remove("is-open");
    document.body.classList.remove("menu-open");
  }
  if (menu && nav) {
    menu.addEventListener("click", () => {
      const expanded = menu.getAttribute("aria-expanded") !== "true";
      menu.setAttribute("aria-expanded", String(expanded));
      nav.classList.toggle("is-open", expanded);
      document.body.classList.toggle("menu-open", expanded);
    });
    nav.querySelectorAll("a").forEach(link => link.addEventListener("click", closeMenu));
    document.addEventListener("keydown", event => { if (event.key === "Escape") closeMenu(); });
    window.addEventListener("resize", () => { if (window.innerWidth > 820) closeMenu(); });
  }

  document.querySelectorAll("[data-year]").forEach(el => { el.textContent = String(new Date().getFullYear()); });
